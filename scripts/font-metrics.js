// Generates src/core/font-metrics.js: advance widths for every bundled font, so
// text can be measured and wrapped identically in Node and in the browser
// without loading font files. Run with `npm run metrics` after changing fonts.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import opentype from 'opentype.js';
import { FONTS, EXTRA_CODEPOINTS } from '../src/core/fonts.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = {};

for (const [key, def] of Object.entries(FONTS)) {
  const buf = readFileSync(path.join(root, 'fonts', def.file));
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const family = font.getEnglishName('typographicFamily') || font.getEnglishName('fontFamily');
  const weight = font.tables.os2?.usWeightClass;
  if (family !== def.family || weight !== def.weight) {
    console.warn(`! ${key}: file says "${family}" ${weight}, registry says "${def.family}" ${def.weight}`);
  }

  const advance = (cp) => {
    const glyph = font.charToGlyph(String.fromCodePoint(cp));
    return glyph && glyph.index !== 0 ? Math.round(glyph.advanceWidth) : 0;
  };
  // Code points 32..255 as a flat array (0 = missing glyph).
  const latin = [];
  for (let cp = 32; cp <= 255; cp++) latin.push(advance(cp));
  const extra = {};
  for (const cp of EXTRA_CODEPOINTS) {
    const w = advance(cp);
    if (w) extra[cp] = w;
  }
  const lower = 'abcdefghijklmnopqrstuvwxyz'.split('').map((c) => advance(c.codePointAt(0)));
  const avg = Math.round(lower.reduce((a, b) => a + b, 0) / lower.length);

  out[key] = {
    upm: font.unitsPerEm,
    asc: font.tables.hhea.ascender,
    desc: font.tables.hhea.descender,
    cap: font.tables.os2?.sCapHeight || Math.round(font.unitsPerEm * 0.7),
    avg,
    latin,
    extra,
  };
  console.log(`${key.padEnd(11)} ${String(family).padEnd(18)} w${weight} upm ${font.unitsPerEm} cap ${out[key].cap}`);
}

const banner = '// Generated by scripts/font-metrics.js. Do not edit by hand.\n';
writeFileSync(
  path.join(root, 'src/core/font-metrics.js'),
  `${banner}export default ${JSON.stringify(out)};\n`,
);
console.log('wrote src/core/font-metrics.js');
